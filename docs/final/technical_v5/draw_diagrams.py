class Canvas:
    def __init__(self,h):
        self.w=1600;self.h=h;self.im=Image.new('RGB',(1600,h),'white');self.d=ImageDraw.Draw(self.im);self.svg=[f'<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="{h}" viewBox="0 0 1600 {h}"><rect width="1600" height="{h}" fill="white"/>']
    def text(self,x,y,s,size=30,color='ink',bold=False):
        color=C.get(color,color); f=ImageFont.truetype(FONT,size)
        self.d.text((x,y),s,font=f,fill=color)
        self.svg.append(f'<text x="{x}" y="{y+size}" fill="{color}" font-family="Microsoft YaHei, sans-serif" font-size="{size}" font-weight="{600 if bold else 400}">{html.escape(s)}</text>')
    def line(self,pts,color='line',width=3,dash=False,arrow=False):
        color=C.get(color,color)
        for a,b in zip(pts,pts[1:]):
            if dash:
                d=math.dist(a,b);n=max(1,int(d/12))
                for j in range(0,n,2):self.d.line([(a[0]+(b[0]-a[0])*j/n,a[1]+(b[1]-a[1])*j/n),(a[0]+(b[0]-a[0])*min(j+1,n)/n,a[1]+(b[1]-a[1])*min(j+1,n)/n)],fill=color,width=width)
            else:self.d.line([a,b],fill=color,width=width)
        points=' '.join(f'{x},{y}' for x,y in pts);self.svg.append(f'<polyline points="{points}" fill="none" stroke="{color}" stroke-width="{width}"'+(' stroke-dasharray="12 9"' if dash else '')+'/>')
        if arrow:
            a,b=pts[-2:];t=math.atan2(b[1]-a[1],b[0]-a[0]);p=[b,(b[0]-17*math.cos(t-.4),b[1]-17*math.sin(t-.4)),(b[0]-17*math.cos(t+.4),b[1]-17*math.sin(t+.4))];self.poly(p,color)
    def poly(self,pts,fill,outline=None):
        fill=C.get(fill,fill);self.d.polygon(pts,fill=fill,outline=C.get(outline,outline) if outline else None)
        self.svg.append(f'<polygon points="'+ ' '.join(f'{x},{y}' for x,y in pts)+f'" fill="{fill}" stroke="{C.get(outline,outline) if outline else fill}" stroke-width="3"/>')
    def box(self,x,y,w,h,title,lines,fill='blue'):
        self.d.rounded_rectangle((x,y,x+w,y+h),radius=12,fill=C[fill],outline='#94ACB5',width=2)
        self.svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="{C[fill]}" stroke="#94ACB5" stroke-width="2"/>')
        self.text(x+24,y+20,title,34,bold=True)
        for i,s in enumerate(lines):self.text(x+24,y+78+i*44,s,29)
    def label(self,y,s):self.text(45,y,s,29,'muted',True)
    def save(self,name):
        self.im.save(ROOT/(name+'.png'));(ROOT/(name+'.svg')).write_text('\n'.join(self.svg+['</svg>']),encoding='utf-8')

